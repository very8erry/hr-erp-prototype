export function codeForItJob(job:string,team:string){const match=(v:string)=>/보안/.test(v)?'135':/서버|프론트|백엔드|개발/.test(v)?'133':/데이터|인프라|네트워크|클라우드/.test(v)?'134':/제품|기획|마케팅|브랜드/.test(v)?'024':/회계|재무|급여/.test(v)?'027':/인사|채용/.test(v)?'026':/영업/.test(v)?'612':/품질/.test(v)?'028':null;return match(job)??match(team)??'029'}
export function itOccupationSeed(employees:EmployeeView[]):OccupationMapping[]{const groups=new Map<string,EmployeeView>();for(const e of employees)groups.set(e.organizationId+'|'+e.job,e);return [...groups.values()].map(e=>({id:'OCC-IT-'+e.organizationId+'-'+e.job,organizationId:e.organizationId,job:e.job,defaultOccupationCode:codeForItJob(e.job,e.organizationName),effectiveFrom:'2025-01-01',effectiveTo:null,source:occupationSource,dictionaryVersion:occupationVersion,manualOverride:false}))}
